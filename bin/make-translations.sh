#!/usr/bin/env bash
#
# Compiles languages/*.po into what WordPress actually loads.
#
# Two outputs per locale:
#
#   spacery-<locale>.mo            PHP strings.
#   spacery-<locale>-<handle>.json JavaScript strings, one file per script handle.
#
# The handle-named form is deliberate. `_load_script_textdomain_from_src()`
# tries `<domain>-<locale>-<handle>.json` in the directory passed to
# `wp_set_script_translations()` *before* falling back to hashing the script's
# URL, so naming files after handles avoids depending on where the plugin is
# installed or what the built file is called.
#
# `wp i18n make-json` splits by source file and names each output after an MD5
# of that path, which is the fallback scheme, not this one. Its files are merged
# into one payload per handle and the originals discarded: Spacery's bundles
# share modules, so a per-source split would need the shared strings duplicated
# across handles anyway.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LANGS="$ROOT/languages"
WP_CLI="${WP_CLI:-wp}"

if command -v "$WP_CLI" >/dev/null 2>&1; then
  WP_RUN=("$WP_CLI")
elif [ -f "$WP_CLI" ]; then
  WP_RUN=(php "$WP_CLI")
else
  echo "wp-cli not found. Install it, or set WP_CLI to a wp-cli.phar." >&2
  exit 1
fi

# Every script handle Spacery registers. The block's handle is generated by
# core from block.json; see generate_block_asset_handle().
HANDLES=(
  spacery-extension
  spacery-settings
  spacery-spacer-editor-script
)

"${WP_RUN[@]}" --allow-root i18n make-mo "$LANGS" "$LANGS"

rm -f "$LANGS"/spacery-*-[0-9a-f]*.json
"${WP_RUN[@]}" --allow-root i18n make-json "$LANGS" --no-purge --pretty-print >/dev/null

for po in "$LANGS"/spacery-*.po; do
  [ -e "$po" ] || continue
  locale="$(basename "$po" .po)"
  locale="${locale#spacery-}"

  LANGS="$LANGS" LOCALE="$locale" HANDLES="${HANDLES[*]}" python3 - <<'PY'
import glob, json, os, re

langs   = os.environ['LANGS']
locale  = os.environ['LOCALE']
handles = os.environ['HANDLES'].split()

merged, header = {}, None

for path in glob.glob(os.path.join(langs, f'spacery-{locale}-*.json')):
    if not re.fullmatch(r'[0-9a-f]{32}', os.path.basename(path)[len(f'spacery-{locale}-'):-5]):
        continue
    with open(path, encoding='utf-8') as handle:
        data = json.load(handle)
    messages = data.get('locale_data', {}).get('messages', {})
    header = header or messages.get('')
    merged.update({k: v for k, v in messages.items() if k})

if not merged:
    raise SystemExit(f'No JavaScript strings found for {locale}.')

payload = {
    'translation-revision-date': '',
    'generator': 'bin/make-translations.sh',
    'domain': 'messages',
    'locale_data': {'messages': {'': header or {'domain': 'messages'}, **merged}},
}

for name in handles:
    payload['source'] = name
    target = os.path.join(langs, f'spacery-{locale}-{name}.json')
    with open(target, 'w', encoding='utf-8') as handle:
        json.dump(payload, handle, ensure_ascii=False, indent='\t')
        handle.write('\n')

print(f'{locale}: {len(merged)} strings into {len(handles)} handle files')
PY
done

# The MD5-named files were only an intermediate step.
rm -f "$LANGS"/spacery-*-[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f].json

echo "Wrote languages/*.mo and languages/*-<handle>.json"
